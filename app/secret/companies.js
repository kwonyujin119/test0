/* 글에서 기업 이름 찾기: 긴 이름부터 찾고, 찾은 자리는 지워서 '에코프로비엠' 안의 '에코프로' 같은 겹침을 막는다. 영문 티커는 낱말 단위로만 */
window.secFindCompanies = function (text, extra) {
  let s = ' ' + String(text || '') + ' ';
  const names = [...new Set([...(extra || []), ...window.SEC_COMPANIES].map(x => String(x || '').trim()).filter(x => x.length >= 2))].sort((a, b) => b.length - a.length);
  const found = [];
  for (const n of names) {
    const latin = /^[A-Za-z0-9.&\- ]+$/.test(n);
    const re = latin ? new RegExp('(^|[^A-Za-z0-9])' + n.replace(/[.*+?^${}()|[\]\\&]/g, '\\$&') + '(?![A-Za-z0-9])', n === n.toUpperCase() ? 'g' : 'gi') : new RegExp(n.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'g');
    if (re.test(s)) { found.push(n); s = s.replace(re, m => ' '.repeat(m.length)); }
  }
  return found;
};
